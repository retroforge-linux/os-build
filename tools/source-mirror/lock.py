#!/usr/bin/env python3
"""Write mirror/sources.lock: every file and git commit the build fetches, for source-mirror.

    tools/source-mirror/lock.py [--arch-record FILE] [--check]

Rows, one per line, whitespace-separated (rf-fetch, rf-seed and sync.sh read them with awk):

    <sha256> file <url> <release>/<asset> <from>                a pinned file
    <sha256> arch <url> <release>/<asset> <bytes>               an Arch Linux Archive file the x86
                                                                Mesa builder's pacman fetches
    <commit> git  <url> <release>/<asset> <dir> <frag> <pkg>    a makepkg git source; its bundle
                                                                holds <commit>; <dir> is makepkg's
                                                                clone, <frag> the #fragment or -

<release>/<asset> is where the object lives on retroforge-linux/source-mirror, named for people:

    sources/<file>                       the kernel, mesa and PKGBUILD source tarballs, under the
                                         name makepkg gives them; holo PKGBUILDs as
                                         holo-<pkg>-<ref>.PKGBUILD
    prebuilt/<file>                      packages/*/prebuilt.pin downloads
    fex-rootfs/<name>-<version>.<ext>    the FEX guest image
    git/<dir>[-<tag>]-<commit12>.bundle
    archlinux-<YYYY.MM.DD>-<repo>/<file> the snapshot's database and package files

Asset names keep [A-Za-z0-9._-] and turn anything else (an epoch's ':') into '_', as GitHub would
rename them otherwise. Two rows wanting one asset name for different content stop the run.

Where the hashes come from:
  - kernel/SOURCE.pin, packages/mesa-x86/guest.pin, packages/*/prebuilt.pin: their sha256.
  - packages/*/source.pin: the PKGBUILD (local, or the holo one at pkgbuild_ref, which is itself a
    file row) and its source[]/source_aarch64[] with sha256sums. A source with only b2sums or SKIP
    is downloaded once here and hashed, so the mirror still pins it.
  - git sources: #tag= and #commit= resolve to a commit (git ls-remote). An unpinned one that the
    package's pinned repo has as a submodule (gamescope's) takes the submodule's recorded commit;
    any other unpinned one takes HEAD now.
  - arch rows: --arch-record, the record tools/source-mirror/record-arch.sh makes from a real run
    of the builder's pacman. Without it, the current snapshot's rows are kept from the old lock.

--check: exit 1 if the lock would change (nothing is written).

The lock is not hashed into rootfs/manifest.lock (packages/inputhash.sh does not read it), so
refreshing it rebuilds nothing.
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCK = ROOT / "mirror" / "sources.lock"
GL = "https://gitlab.steamos.cloud"
ARCH = "aarch64"
HEX64 = re.compile(r"^[0-9a-f]{64}$")
HEX40 = re.compile(r"^[0-9a-f]{40}$")
ARCHIVE = re.compile(r"^https://archive\.archlinux\.org/repos/(\d{4})/(\d\d)/(\d\d)/([a-z0-9-]+)/os/[a-z0-9_]+/([^/]+)$")

HEADER = """\
# source-mirror lock -- GENERATED by tools/source-mirror/lock.py, do not hand-edit.
# Every file and git commit the build fetches, by hash, and where retroforge-linux/source-mirror
# keeps its copy (<release>/<asset>). tools/source-mirror/rf-fetch and rf-seed take the copy first
# and the URL second, checking the hash either way; tools/source-mirror/sync.sh fills the mirror
# from this file. See tools/source-mirror/README.md.
#
# <sha256|commit>  <kind>  <url>  <release>/<asset>  <from | bytes | dir frag pkg>
"""


def asset(name):
    name = re.sub(r"[^A-Za-z0-9._-]", "_", name).strip(".")
    return name or "unnamed"


def pin(path):
    out = {}
    for line in Path(path).read_text().splitlines():
        m = re.match(r"^([a-z_0-9]+):\s*(.*?)\s*$", line)
        if m and not line.startswith("#"):
            out.setdefault(m.group(1), m.group(2))
    return out


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "retroforge-source-mirror"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def sha256_url(url):
    h = hashlib.sha256()
    req = urllib.request.Request(url, headers={"User-Agent": "retroforge-source-mirror"})
    with urllib.request.urlopen(req, timeout=120) as r:
        for chunk in iter(lambda: r.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def pkgbuild_sources(pkgbuild):
    """(source, sha256-or-empty) for source[] and source_<ARCH>[], as makepkg sees them."""
    script = r'''
source "$1" >/dev/null 2>&1 || exit 1
for i in "${!source[@]}"; do printf "%s\t%s\n" "${source[$i]}" "${sha256sums[$i]:-}"; done
eval "s=(\"\${source_$2[@]}\"); h=(\"\${sha256sums_$2[@]}\")"
for i in "${!s[@]}"; do printf "%s\t%s\n" "${s[$i]}" "${h[$i]:-}"; done
'''
    out = subprocess.run(["bash", "-c", script, "_", str(pkgbuild), ARCH],
                         check=True, capture_output=True, text=True).stdout
    return [tuple((line.split("\t") + [""])[:2]) for line in out.splitlines() if line]


def ls_remote(url, *refs):
    out = subprocess.run(["git", "ls-remote", url, *refs], check=True, capture_output=True,
                         text=True, timeout=300).stdout
    return dict(reversed(line.split("\t")) for line in out.splitlines() if "\t" in line)


def resolve(url, frag):
    """The commit a git+URL#frag source checks out."""
    kind, _, val = frag.partition("=")
    if kind == "commit" and HEX40.match(val):
        return val
    if kind in ("tag", "commit"):
        refs = ls_remote(url, f"refs/tags/{val}", f"refs/tags/{val}^{{}}", f"refs/heads/{val}")
        for ref in (f"refs/tags/{val}^{{}}", f"refs/tags/{val}", f"refs/heads/{val}"):
            if ref in refs:
                return refs[ref]
        raise SystemExit(f"lock.py: {url} has no {frag}")
    if kind == "branch":
        return ls_remote(url, f"refs/heads/{val}")[f"refs/heads/{val}"]
    return ls_remote(url, "HEAD")["HEAD"]


def norm(url):
    url = re.sub(r"^git\+", "", url).split("#")[0].split("?")[0].rstrip("/")
    return re.sub(r"\.git$", "", re.sub(r"^[a-z+]+://", "", url)).lower()


def submodule_commits(url, commit):
    """{normalized submodule url: commit} recorded in url's tree at commit."""
    with tempfile.TemporaryDirectory() as d:
        subprocess.run(["git", "clone", "--quiet", "--bare", "--filter=blob:none", url, d],
                       check=True, timeout=1800)
        gm = subprocess.run(["git", "-C", d, "show", f"{commit}:.gitmodules"],
                            capture_output=True, text=True)
        if gm.returncode:
            return {}
        subs, cur = {}, None
        for line in gm.stdout.splitlines():
            m = re.match(r'\s*\[submodule "(.*)"\]', line)
            if m:
                cur = m.group(1)
            m = re.match(r"\s*(path|url)\s*=\s*(.*)", line)
            if m and cur:
                subs.setdefault(cur, {})[m.group(1)] = m.group(2).strip()
        tree = subprocess.run(["git", "-C", d, "ls-tree", "-r", commit], check=True,
                              capture_output=True, text=True).stdout
        links = {}
        for line in tree.splitlines():
            meta, path = line.split("\t", 1)
            if meta.split()[1] == "commit":
                links[path] = meta.split()[2]
        return {norm(s["url"]): links[s["path"]] for s in subs.values()
                if "url" in s and s.get("path") in links}


def git_asset(dirname, frag, commit):
    """git/<dir>-<tag>-<commit12>.bundle, or git/<dir>-<commit12>.bundle with no tag to name."""
    label = frag.partition("=")[2]
    if not label or HEX40.match(label):
        return "git/" + asset(f"{dirname}-{commit[:12]}") + ".bundle"
    return "git/" + asset(f"{dirname}-{label}-{commit[:12]}") + ".bundle"


def package_rows(pin_path):
    p = pin(pin_path)
    name = p.get("name") or pin_path.parent.name
    rows = []
    if p.get("pkgbuild_local"):
        pkgbuild, tmp = pin_path.parent / p["pkgbuild_local"], None
    else:
        url = f"{GL}/{p['pkgbuild_repo']}/-/raw/{p['pkgbuild_ref']}/{p['pkgbuild_path']}/PKGBUILD"
        data = fetch(url)
        ref12 = p["pkgbuild_ref"][:12]
        rows.append((hashlib.sha256(data).hexdigest(), "file", url,
                     "sources/" + asset(f"holo-{name}-{ref12}.PKGBUILD"), f"holo:{name}"))
        tmp = tempfile.NamedTemporaryFile("wb", suffix="PKGBUILD", delete=False)
        tmp.write(data)
        tmp.close()
        pkgbuild = Path(tmp.name)
    try:
        sources = pkgbuild_sources(pkgbuild)
    finally:
        if tmp:
            os.unlink(tmp.name)

    gits = []
    for src, sha in sources:
        target, _, url = src.rpartition("::")
        if url.startswith("git+"):
            plain = url[4:]
            frag = plain.split("#", 1)[1] if "#" in plain else "-"
            plain = plain.split("#")[0].split("?")[0]
            gits.append((target or os.path.basename(plain).removesuffix(".git"), plain, frag))
        elif re.match(r"^(https?|ftp)://", url):
            if not HEX64.match(sha):
                print(f"lock.py: {name}: hashing {url} (no sha256 in the PKGBUILD)", file=sys.stderr)
                sha = sha256_url(url)
            rows.append((sha, "file", url, f"sources/{asset(target or url.rsplit('/', 1)[1])}", name))

    pinned = [(d, u, f, resolve(u, f)) for d, u, f in gits if f != "-"]
    subs = {}
    if any(f == "-" for _, _, f in gits):
        for _, u, _, c in pinned:
            subs.update(submodule_commits(u, c))
    for d, u, f in gits:
        if f == "-":
            c = subs.get(norm(u))
            if not c:
                print(f"lock.py: {name}: {u} is unpinned; taking HEAD now", file=sys.stderr)
                c = resolve(u, "-")
            rows.append((c, "git", u, git_asset(d, f, c), f"{d} - {name}"))
    for d, u, f, c in pinned:
        rows.append((c, "git", u, git_asset(d, f, c), f"{d} {f} {name}"))
    return rows


def arch_row(sha, size, url):
    m = ARCHIVE.match(url)
    if not m:
        raise SystemExit(f"lock.py: not an archive.archlinux.org repo URL: {url}")
    y, mo, d, repo, file = m.groups()
    return (sha, "arch", url, f"archlinux-{y}.{mo}.{d}-{repo}/{asset(file)}", size)


def old_rows():
    rows = []
    if LOCK.exists():
        for line in LOCK.read_text().splitlines():
            if line.strip() and not line.startswith("#"):
                f = line.split(None, 4)
                rows.append(tuple(f) if len(f) == 5 else tuple(f + [""] * (5 - len(f))))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arch-record", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = []
    k = pin(ROOT / "kernel" / "SOURCE.pin")
    rows.append((k["sha256"], "file", k["url"], f"sources/{asset(k['url'].rsplit('/', 1)[1])}",
                 "kernel/SOURCE.pin"))
    g = pin(ROOT / "packages" / "mesa-x86" / "guest.pin")
    base, _, ext = g["url"].rsplit("/", 1)[1].rpartition(".")
    rows.append((g["sha256"], "file", g["url"], "fex-rootfs/" + asset(f"{base}-{g['version']}.{ext}"),
                 "packages/mesa-x86/guest.pin"))
    for pp in sorted((ROOT / "packages").glob("*/prebuilt.pin")):
        p = pin(pp)
        rows.append((p["sha256"], "file", p["url"], f"prebuilt/{asset(p['url'].rsplit('/', 1)[1])}",
                     f"packages/{pp.parent.name}/prebuilt.pin"))
    for sp in sorted((ROOT / "packages").glob("*/source.pin")):
        rows += package_rows(sp)

    snapshot = pin(ROOT / "packages" / "mesa-x86" / "builder.pin")["snapshot"]
    if args.arch_record:
        for line in args.arch_record.read_text().splitlines():
            sha, size, url = line.split()
            rows.append(arch_row(sha, size, url))
    else:
        rows += [r for r in old_rows() if r[1] == "arch" and f"/repos/{snapshot}/" in r[2]]

    seen, where, out = set(), {}, []
    order = {"file": 0, "git": 1, "arch": 2}
    for r in sorted(rows, key=lambda r: (order[r[1]], r[2], r[4])):
        key = (r[1], r[2], r[4].split()[1] if r[1] == "git" else "")
        if key in seen:
            continue
        seen.add(key)
        if where.setdefault(r[3], r[0]) != r[0]:
            raise SystemExit(f"lock.py: {r[3]} would hold both {where[r[3]]} and {r[0]} ({r[2]})")
        out.append(" ".join(x for x in r if x))
    text = HEADER + "\n".join(out) + "\n"
    if args.check:
        same = LOCK.exists() and LOCK.read_text() == text
        print("mirror/sources.lock is current" if same else "mirror/sources.lock is stale")
        sys.exit(0 if same else 1)
    LOCK.parent.mkdir(exist_ok=True)
    LOCK.write_text(text)
    n = {k: sum(1 for r in out if r.split()[1] == k) for k in order}
    print(f"mirror/sources.lock: {n['file']} files, {n['git']} git commits, {n['arch']} arch files")


if __name__ == "__main__":
    main()
